import { useEffect, useState } from 'react';
import { MotionConfig, motion, AnimatePresence } from 'motion/react';
import { IconContext, WarningCircle, Cpu, Sparkle } from '@phosphor-icons/react';
import { api } from './api.js';
import { readStored, writeStored } from './lib/useActivity.js';
import LearnerSheet from './components/Sidebar.jsx';
import Studio from './components/Studio.jsx';
import Vault from './components/Vault.jsx';
import SessionsView from './components/SessionsView.jsx';
import { Skeleton } from './components/ui.jsx';

const VIEWS = [
  { id: 'studio', label: 'Studio' },
  { id: 'vault', label: 'Vault' },
  { id: 'sessions', label: 'Archive' },
];

function Masthead({ view, onView, llm }) {
  return (
    <header className="sticky top-0 z-20 border-b border-line bg-paper/85 backdrop-blur-md">
      <div className="mx-auto flex h-16 max-w-[1400px] items-center gap-6 px-4 lg:px-8">
        <div className="flex items-baseline gap-2">
          <span className="font-serif text-2xl font-medium tracking-tight">Apex</span>
          <span className="hidden text-sm text-ink-3 sm:inline">English studio</span>
        </div>
        <nav aria-label="Main" className="flex gap-1 sm:ml-6">
          {VIEWS.map((v) => (
            <button
              key={v.id}
              onClick={() => onView(v.id)}
              aria-current={view === v.id ? 'page' : undefined}
              className={`relative h-9 rounded-full px-3 text-sm font-medium transition-colors ${view === v.id ? 'text-ink' : 'text-ink-3 hover:text-ink'}`}
            >
              {view === v.id && <motion.span layoutId="nav-pill" className="absolute inset-0 rounded-full bg-sunk" transition={{ type: 'spring', stiffness: 420, damping: 36 }} />}
              <span className="relative">{v.label}</span>
            </button>
          ))}
        </nav>
        <span className="ml-auto hidden items-center gap-1.5 text-xs text-ink-3 md:inline-flex" title={llm ? 'Feedback is generated by the Claude API' : 'Set ANTHROPIC_API_KEY on the server for Claude feedback'}>
          {llm ? <Sparkle size={14} /> : <Cpu size={14} />}
          {llm ? 'Claude feedback' : 'Offline feedback'}
        </span>
      </div>
    </header>
  );
}

function LoadingShell() {
  return (
    <div className="mx-auto grid max-w-[1400px] gap-10 px-4 py-10 lg:grid-cols-[264px_minmax(0,1fr)] lg:px-8">
      <div className="space-y-4">
        <Skeleton className="h-20 w-40" />
        <Skeleton className="h-3 w-full" />
        <Skeleton className="h-40 w-full" />
      </div>
      <div className="space-y-4">
        <Skeleton className="h-10 w-72" />
        <Skeleton className="h-[420px] w-full rounded-2xl" />
      </div>
    </div>
  );
}

export default function App() {
  const [profile, setProfile] = useState(null);
  const [health, setHealth] = useState(null);
  const [error, setError] = useState(null);
  const [view, setView] = useState(() => {
    const v = readStored('coach.view', 'studio');
    return VIEWS.some((x) => x.id === v) ? v : 'studio';
  });
  const [refreshKey, setRefreshKey] = useState(0);

  useEffect(() => {
    Promise.all([api.profile(), api.health()])
      .then(([p, h]) => {
        setProfile(p);
        setHealth(h);
      })
      .catch((e) => setError(e.message));
  }, []);

  useEffect(() => writeStored('coach.view', view), [view]);

  function onActivitySaved(result) {
    setProfile(result.profile);
    setRefreshKey((k) => k + 1);
  }

  return (
    <MotionConfig reducedMotion="user">
      <IconContext.Provider value={{ size: 18, weight: 'regular' }}>
        <Masthead view={view} onView={setView} llm={health?.llm} />
        {error ? (
          <div className="mx-auto max-w-lg px-4 py-24">
            <div className="flex items-center gap-2 font-medium text-brick">
              <WarningCircle size={22} /> The coach server is not reachable
            </div>
            <p className="mt-2 text-ink-2">{error}</p>
            <p className="mt-4 text-sm text-ink-3">
              Start it with <code className="rounded bg-sunk px-1.5 py-0.5 font-mono">npm run dev</code> in <code className="font-mono">english-coach/app</code>, then reload.
            </p>
          </div>
        ) : !profile ? (
          <LoadingShell />
        ) : (
          <div className="mx-auto grid min-h-[calc(100dvh-4rem)] max-w-[1400px] gap-8 px-4 py-8 lg:grid-cols-[264px_minmax(0,1fr)] lg:gap-14 lg:px-8 lg:py-10">
            <LearnerSheet profile={profile} />
            <main className="min-w-0">
              <AnimatePresence mode="wait">
                <motion.div key={view} initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0, y: -4 }} transition={{ duration: 0.35, ease: [0.16, 1, 0.3, 1] }}>
                  {view === 'studio' && <Studio profile={profile} onActivitySaved={onActivitySaved} refreshKey={refreshKey} />}
                  {view === 'vault' && <Vault refreshKey={refreshKey} profile={profile} />}
                  {view === 'sessions' && <SessionsView refreshKey={refreshKey} />}
                </motion.div>
              </AnimatePresence>
            </main>
          </div>
        )}
      </IconContext.Provider>
    </MotionConfig>
  );
}
