'use client';

import { useEffect, useState } from 'react';
import { MotionConfig, motion, AnimatePresence } from 'motion/react';
import { IconContext, WarningCircle, Cpu, Sparkle, SignOut } from '@phosphor-icons/react';
import { api, refreshOnFocus } from '@/api';
import { readStored, writeStored } from '@/lib/useActivity';
import LearnerSheet from '@/components/Sidebar';
import Studio from '@/components/Studio';
import Vault from '@/components/Vault';
import SessionsView from '@/components/SessionsView';
import CoachChat from '@/components/CoachChat';
import Gatekeeper from '@/components/Gatekeeper';
import { Skeleton } from '@/components/ui';

const VIEWS = [
  { id: 'studio', label: 'Studio' },
  { id: 'coach', label: 'Coach' },
  { id: 'vault', label: 'Vault' },
  { id: 'sessions', label: 'Archive' },
];

function Masthead({ view, onView, llm, onLogout }) {
  return (
    <header className="sticky top-0 z-20 border-b border-line bg-paper/85 backdrop-blur-md">
      <div className="mx-auto flex h-16 max-w-[1400px] items-center gap-2 px-4 sm:gap-6 lg:px-8">
        <div className="flex shrink-0 items-baseline gap-2">
          <span className="hidden text-sm text-ink-3 xl:inline">Özgür Deveci</span>
          <span className="hidden text-line-strong xl:inline" aria-hidden>
            |
          </span>
          <span className="font-serif text-2xl font-medium tracking-tight">Lumos</span>
          <span className="hidden text-sm text-ink-3 md:inline">AI English Coach</span>
          <span className="hidden rounded-full border border-line-strong px-1.5 py-px font-mono text-[10px] text-ink-3 lg:inline">v1.0</span>
        </div>
        <nav aria-label="Main" className="flex gap-0.5 sm:ml-4 sm:gap-1">
          {VIEWS.map((v) => (
            <button
              key={v.id}
              onClick={() => onView(v.id)}
              aria-current={view === v.id ? 'page' : undefined}
              className={`relative h-9 rounded-full px-2 text-sm sm:px-3 font-medium transition-colors ${view === v.id ? 'text-ink' : 'text-ink-3 hover:text-ink'}`}
            >
              {view === v.id && <motion.span layoutId="nav-pill" className="absolute inset-0 rounded-full bg-sunk" transition={{ type: 'spring', stiffness: 420, damping: 36 }} />}
              <span className="relative">{v.label}</span>
            </button>
          ))}
        </nav>
        <span
          className="ml-auto hidden items-center gap-1.5 text-xs text-ink-3 md:inline-flex"
          title={llm ? 'Feedback is generated by Gemini' : 'Set GEMINI_API_KEY in .env on the server for AI feedback'}
        >
          {llm ? <Sparkle size={14} /> : <Cpu size={14} />}
          {llm ? 'Gemini feedback' : 'Offline feedback'}
        </span>
        {onLogout && (
          <button
            onClick={onLogout}
            className="ml-auto -mr-1.5 grid size-9 shrink-0 place-items-center rounded-full text-ink-3 sm:mr-0 hover:bg-sunk hover:text-ink md:ml-0"
            aria-label="Lock"
            title="Lock"
          >
            <SignOut size={18} />
          </button>
        )}
      </div>
    </header>
  );
}

function LoadingShell() {
  return (
    <div className="mx-auto grid max-w-[1400px] gap-10 px-4 py-10 lg:grid-cols-[264px_minmax(0,1fr)] lg:px-8">
      <div className="space-y-4">
        <Skeleton className="h-20 w-40" />
        <Skeleton className="h-3 w-full" />
        <Skeleton className="h-40 w-full" />
      </div>
      <div className="space-y-4">
        <Skeleton className="h-10 w-72" />
        <Skeleton className="h-[420px] w-full rounded-2xl" />
      </div>
    </div>
  );
}

export default function CoachApp() {
  const [profile, setProfile] = useState(null);
  const [health, setHealth] = useState(null);
  const [error, setError] = useState(null);
  const [view, setView] = useState('studio');
  const [refreshKey, setRefreshKey] = useState(0);
  // null while checking; then the lock screen until the PIN is accepted
  const [auth, setAuth] = useState<{ required: boolean; authenticated: boolean } | null>(null);

  useEffect(() => {
    const v = readStored('coach.view', 'studio');
    if (VIEWS.some((x) => x.id === v)) setView(v);
    // An expired session makes any api.php call answer 401: show the lock screen again.
    const lock = () => setAuth((a) => ({ required: true, ...a, authenticated: false }));
    window.addEventListener('lumos:locked', lock);
    api
      .authStatus()
      .then((a) => {
        setAuth(a);
        setHealth({ llm: a.ai, model: a.model });
      })
      .catch((e) => setError(e.message));
    return () => window.removeEventListener('lumos:locked', lock);
  }, []);

  useEffect(() => {
    if (!auth?.authenticated) return undefined;
    api
      .profile()
      .then(setProfile)
      .catch((e) => !e.locked && setError(e.message));
    // Changes saved from another device show up when this tab is focused again.
    return refreshOnFocus(() =>
      api.profile().then((p) => {
        setProfile(p);
        setRefreshKey((k) => k + 1);
      }),
    );
  }, [auth?.authenticated]);

  async function logout() {
    await api.logout().catch(() => {});
    setProfile(null);
    setAuth((a) => ({ ...a, authenticated: false }));
  }

  useEffect(() => writeStored('coach.view', view), [view]);

  function onActivitySaved(result) {
    setProfile(result.profile);
    setRefreshKey((k) => k + 1);
  }

  return (
    <MotionConfig reducedMotion="user">
      <IconContext.Provider value={{ size: 18, weight: 'regular' }}>
        {auth && !auth.authenticated && !error ? (
          <Gatekeeper onUnlock={() => setAuth((a) => ({ ...a, authenticated: true }))} />
        ) : (
          <>
            <Masthead view={view} onView={setView} llm={health?.llm} onLogout={auth?.required ? logout : null} />
            {error ? (
              <div className="mx-auto max-w-lg px-4 py-24">
                <div className="flex items-center gap-2 font-medium text-brick">
                  <WarningCircle size={22} /> Lumos cannot reach its data
                </div>
                <p className="mt-2 text-ink-2">{error}</p>
                <p className="mt-4 text-sm text-ink-3">
                  Check that <code className="rounded bg-sunk px-1.5 py-0.5 font-mono">api.php</code>, <code className="font-mono">config.php</code> and the <code className="font-mono">.env</code>{' '}
                  file are next to <code className="font-mono">index.html</code> on the host, then reload.
                </p>
              </div>
            ) : !profile ? (
              <LoadingShell />
            ) : (
              <div className="mx-auto grid min-h-[calc(100dvh-4rem)] max-w-[1400px] gap-8 px-4 py-8 lg:grid-cols-[264px_minmax(0,1fr)] lg:gap-14 lg:px-8 lg:py-10">
                <LearnerSheet profile={profile} refreshKey={refreshKey} />
                <main className="min-w-0">
                  <AnimatePresence mode="wait">
                    <motion.div key={view} initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0, y: -4 }} transition={{ duration: 0.35, ease: [0.16, 1, 0.3, 1] as const }}>
                      {view === 'studio' && <Studio profile={profile} onActivitySaved={onActivitySaved} refreshKey={refreshKey} />}
                      {view === 'coach' && <CoachChat llm={health?.llm} />}
                      {view === 'vault' && <Vault refreshKey={refreshKey} profile={profile} onReviewed={onActivitySaved} />}
                      {view === 'sessions' && <SessionsView refreshKey={refreshKey} />}
                    </motion.div>
                  </AnimatePresence>
                </main>
              </div>
            )}
          </>
        )}
      </IconContext.Provider>
    </MotionConfig>
  );
}
